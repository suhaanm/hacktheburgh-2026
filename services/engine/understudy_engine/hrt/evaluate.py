"""The report sections for the HRT track: the recorded held-out results of ``hrt.run``, shaped for ``evals/report.json`` and the Evidence page.

Read-only: the harness (`make eval`) never runs the held-out command; it reads ``evals/hrt/results/heldout_<part>.json``. A part that has not been run is
``pending`` with the reason, and a dev result is never shown as evidence.
"""
from __future__ import annotations

import json
from typing import Any

from understudy_engine.store.paths import evals_dir

GEN = "synthetic"
WORLD_LABEL = {"v1": "v1 world (fresh seeds, no shift)", "markov": "shifted: markov", "latent_skill": "shifted: latent skill", "process_trace": "shifted: process trace",
               "route_no_drift": "error risk, no drift", "route_drift": "error risk, rule change at case 1,500"}
WORLD_ORDER = tuple(WORLD_LABEL)


def _r(x: Any, nd: int = 4) -> Any:
    return None if x is None else round(float(x), nd)


def _ci(ci: Any, nd: int = 4) -> Any:
    return [_r(ci[0], nd), _r(ci[1], nd)] if ci and ci[0] is not None else None


def recorded(part: str) -> dict[str, Any] | None:
    p = evals_dir() / "hrt" / "results" / f"heldout_{part}.json"
    try:
        if not p.is_file() or p.is_symlink():
            return None
        d = json.loads(p.read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else None
    except (OSError, ValueError):
        return None


LEDGER_LIMITS = [
    ("hrt-ledger-ours", "high", "Every world is generated by us. The shifted worlds differ in structure from the world the models were fitted on, but they are still ours; a held-out replicate catches overfitting to one noise draw, never 'the model learned our generators'."),
    ("hrt-ledger-same-types", "medium", "The v1 world draws new people of the same four persona types the models were fitted on. A new type of worker, or a new kind of task, is what the shifted worlds stand in for."),
    ("hrt-ledger-guard-guarantee", "medium", "The guard's bound on false flags assumes each episode's loss difference has conditional mean at most zero given the past. Episodes of one person are not independent, so the bound is a design target that the no-drift deployments check, not a proof."),
    ("hrt-ledger-eight", "medium", "Eight deployments per world give wide intervals for guard counts and for the strategy comparison; counts are shown with exact intervals."),
    ("hrt-ledger-one-direction", "medium", "The guard compares the model with a naive predictor. A model that drifts but stays better than that predictor is not flagged (the error-risk world after the rule change); the loss of calibration shows in the reliability table and the intercept, and nothing recalibrates the model in this version."),
    ("hrt-ledger-no-live", "medium", "The ledger is built and tested, but the running product has recorded no live predictions yet, so no real prospective result exists. These are replays of simulated time."),
    ("hrt-ledger-oracle", "low", "The oracle strategy picks the better of two predictors in hindsight; it bounds what is possible and is not implementable."),
]
DECISION_LIMITS = [
    ("hrt-decisions-ours", "high", "Every decision is scored in a simulator we wrote, with a cost we chose. The ordering of policies is a statement about these mechanisms, not about real routines, real reviewers, real workdays or real people."),
    ("hrt-decisions-costs", "medium", "The review minutes per case, the cost of an escaped error, the build cost b, the ratio of a collision's cost to a finished run's value (L/G) and the intervention reward are assumptions; each row prints a sweep or says which cost it hangs on."),
    ("hrt-decisions-routing-signals", "medium", "In the routing generator the worker's check, the agent's stated confidence and the worker's trace are drawn from the realised error. Part of the model's edge over random review is signal our generator hands it."),
    ("hrt-decisions-build-now", "medium", "At the pack's own build costs (4 to 9 manual runs) building at once is cheaper than the shipped build-timing rule in this simulation; the rule beats break-even, the classical reference, which is the registered primary contrast."),
    ("hrt-decisions-family", "low", "Four primary contrasts were registered; every other cell is exploratory and is never used to say a rule works. The adjusted level is Bonferroni, which is conservative."),
]


def _claim_text(c: dict[str, Any]) -> str:
    ev = c.get("evidence")
    if c["id"] == "P1" and isinstance(ev, dict):
        return "; ".join(f"against {k.replace('_', ' ')} {v['est']:+.4f} {_ci(v['ci'])}" for k, v in ev.items())
    if c["id"] == "P2" and isinstance(ev, dict):
        return f"slope {ev['slope']:.3f} {_ci(ev['slope_ci'], 3)}, intercept {ev['intercept']:+.3f} {_ci(ev['intercept_ci'], 3)}"
    if c["id"] in ("P3", "P4b") and isinstance(ev, dict):
        parts = []
        for f, v in ev.items():
            if c["id"] == "P3":
                parts.append(f"{f}: {'worse' if v['worse'] else 'better' if v['better'] else 'no clear difference'} ({v['est']:+.3f} {_ci(v['ci'], 3)} against {v['baseline'].replace('_', ' ')})")
            else:
                parts.append(f"{f}: {v['state']}, flagged {v['flags']} of {v['of']}")
        return "; ".join(parts)
    if c["id"] == "P4a" and isinstance(ev, dict):
        return f"flagged {ev['flags']} of {ev['of']} {_ci(ev['ci'], 3)}"
    if c["id"] == "P4c" and isinstance(ev, dict):
        return f"guarded minus always-model {ev['est']:+.4f} nats {_ci(ev['ci'])}"
    if c["id"] == "P4d":
        if isinstance(ev, dict):
            return "; ".join(f"{f}: model worse by {v['model_minus_fallback']:.3f}, guard saves {-v['est']:.3f} {_ci(v['ci'], 3)}" for f, v in ev.items())
        return str(ev)
    if c["id"] == "P5" and isinstance(ev, dict):
        return f"truncated CRPS {ev['model']:.2f} s against {ev['frozen_km']:.2f} s for the Kaplan-Meier constant; difference {ev['est']:+.3f} s {_ci(ev['ci'], 3)}"
    if c["id"] == "P6a" and isinstance(ev, dict):
        return f"model minus online base {ev['vs_online']['est']:+.4f} {_ci(ev['vs_online']['ci'])}, slope {ev['slope']:.3f} {_ci(ev['slope_ci'], 3)}"
    if c["id"] == "P6b" and isinstance(ev, dict):
        return (f"after the change the model minus online base is {ev['post_change_model_vs_online_base']['est']:+.4f} {_ci(ev['post_change_model_vs_online_base']['ci'])} "
                f"({'worse' if ev['post_change_model_worse'] else 'still better'}); flagged {ev['flags_drift']} with drift, {ev['flags_no_drift']} without")
    return json.dumps(ev, default=float)[:200]


def shape_ledger(res: dict[str, Any]) -> dict[str, Any]:
    worlds = res["worlds"]
    rows, guard_rows = [], []
    n_preds = 0
    for key in WORLD_ORDER:
        w = worlds.get(key)
        if not w:
            continue
        n_preds += int(w["n_bins"])
        pred = w["scores"]["predictors"]
        cal = pred["model"]["calibration"]
        mb = w["model_vs_best_naive"]
        rows.append({"world": WORLD_LABEL[key], "deployments": w["n_deployments"], "people_or_blocks": w["n_people"], "predictions": w["n_bins"],
                     "model_log_loss": _r(pred["model"]["log_loss"]["est"]), "model_log_loss_ci": _ci(pred["model"]["log_loss"]["ci"]),
                     "best_naive": mb["baseline"], "best_naive_log_loss": _r(w["best_naive_pooled_log_loss"]),
                     "model_minus_best_naive": _r(mb["est"]), "model_minus_best_naive_ci": _ci(mb["ci"]), "verdict": mb["verdict"],
                     "calibration_slope": _r(cal["slope"], 3), "calibration_slope_ci": _ci(cal["slope_ci"], 3), "calibration_intercept": _r(cal["intercept"], 3),
                     "calibration_intercept_ci": _ci(cal["intercept_ci"], 3), "ece": _r(pred["model"]["ece"]), "guard_flags": f"{w['guard']['flags']} of {w['guard']['of']}"})
        m = w["guard"]["strategies"]["mean"]
        gap = w["guard"]["strategies"]
        guard_rows.append({"world": WORLD_LABEL[key], "flags": w["guard"]["flags"], "of": w["guard"]["of"], "flag_rate_ci": _ci(w["guard"]["flag_rate_ci"], 3),
                           "always_model": _r(m["always_model"]["est"]), "always_fallback": _r(m["always_fallback"]["est"]), "guarded": _r(m["guarded"]["est"]), "oracle": _r(m["oracle"]["est"]),
                           "regret_always_model": _r(m["regret_always_model"]["est"]), "regret_guarded": _r(m["regret_guarded"]["est"]),
                           "guarded_minus_always_model": _r(gap["guarded_minus_always_model"]["est"]), "guarded_minus_always_model_ci": _ci(gap["guarded_minus_always_model"]["ci"]),
                           "share_on_fallback": _r(m["share_on_fallback"]["est"], 3)})
    claims = [{"id": c["id"], "claim": c["claim"], "result": "passed" if c["pass"] is True else "not passed" if c["pass"] is False else "not applicable", "evidence": _claim_text(c)} for c in res["claims"]]
    n_pass = sum(c["result"] == "passed" for c in claims)
    n_applic = sum(c["result"] != "not applicable" for c in claims)
    v1 = worlds["v1"]
    pv = v1["scores"]["paired_log_loss_vs"]
    bits = [f"Of {n_applic} registered claims, {n_pass} passed and {n_applic - n_pass} did not (all are listed, none changed after the run)."]
    if "online_base" in pv:
        bits.append(f"In the world it was fitted for, the deployed model's prospective log loss was {pv['online_base']['est']:+.3f} {_ci(pv['online_base']['ci'], 3)} against the online base rate.")
    worse = [WORLD_LABEL[k].replace("shifted: ", "") for k in ("markov", "latent_skill", "process_trace") if k in worlds and worlds[k]["model_vs_best_naive"]["verdict"] == "a worse"]
    bits.append(f"In {len(worse)} of 3 shifted worlds it was worse than the best naive predictor{(' (' + ', '.join(worse) + ')') if worse else ''}.")
    return {
        "meta": {"origin": GEN, "n": n_preds, "n_unit": "scored predictions", "split": "models frozen at deployment on a training pool; every prediction written to a hash-chained ledger before its outcome and scored forward in time, on new seeds",
                 "interval_level": 0.95, "note": "Cluster bootstrap resampling people (error risk: blocks of 100 cases), B = 2000, paired across predictors. Pre-registered in evals/hrt/PLAN.md; run once on held-out seeds.", "generated_at": res.get("generated_at") or "1970-01-01T00:00:00Z"},
        "statement": " ".join(bits),
        "label": "synthetic, held-out seeds, single frozen run; the ledger has recorded no live predictions yet",
        "rows": claims, "worlds": rows, "guard": guard_rows,
        "reliability_v1": [{k: b[k] for k in ("p_mean", "freq", "n", "freq_lo", "freq_hi", "lo", "hi")} for b in v1["scores"]["predictors"]["model"]["reliability"]],
        "reliability_v1_online_base": [{k: b[k] for k in ("p_mean", "freq", "n", "lo", "hi")} for b in v1["scores"]["predictors"]["online_base"]["reliability"]],
        "design": res.get("design"), "split_label": res.get("split_label"), "code_fingerprint": res.get("code_fingerprint"),
        "limitations": [{"id": i, "severity": s, "text": t} for i, s, t in LEDGER_LIMITS],
    }


def _row_values(row: dict[str, Any]) -> dict[str, Any]:
    pc = row["primary"]
    cell_key = {"D1": "8", "D2": "0.3", "D3": "9", "D4": "all"}[row["id"]]
    cell = row["cells"][cell_key]
    pol = cell["policies"]
    shipped_key = next(k for k in pol if k.startswith("shipped") or k == "model")
    naive_key = next(k for k, c in cell["contrasts"].items() if c["primary"]).split("_minus_", 1)[1]
    gk = next(k for k in cell if k.startswith("gap_closed"))
    g = cell[gk]
    return {"id": row["id"], "decision": row["decision"], "unit": row["unit"], "better": row["direction"],
            "shipped_rule": _r(pol[shipped_key]["est"], 3), "naive_policy": naive_key.replace("_", " "), "naive_value": _r(pol[naive_key]["est"], 3),
            "oracle_value": _r(pol[next(k for k in pol if "oracle" in k and "prior" not in k and "true" not in k)]["est"], 3),
            "primary_contrast": _r(pc["est"], 3), "ci95": _ci(pc["ci95"], 3), "ci_adjusted_98_75": _ci(pc["ci_adjusted"], 3), "verdict": pc["verdict"],
            "share_of_naive_to_oracle_gap_closed": _r(g.get("share"), 3), "share_ci": _ci(g.get("ci"), 3), "replicates": row["replicates"]}


def shape_decisions(res: dict[str, Any]) -> dict[str, Any]:
    rows = [_row_values(r) for r in res["rows"]]
    n = sum(res["replicates"].values())
    fam = res["primary_family"]
    wins = [r["id"] for r in rows if r["verdict"] == "win"]
    cue = (res.get("recorded") or [{}])[0]
    stmt = (f"Four registered contrasts, each the shipped rule against a naive policy on fresh simulated worlds, judged at the Bonferroni-adjusted level ({fam['adjusted_level']:.2%}): "
            f"{len(wins)} of 4 are wins ({', '.join(wins) if wins else 'none'}). Costs that the data cannot supply are swept, not assumed.")
    return {
        "meta": {"origin": GEN, "n": n, "n_unit": "simulated worlds", "split": "fresh replicate worlds on new seeds; shipped, naive and oracle policies scored on the same world; paired bootstrap over worlds",
                 "interval_level": 0.95, "note": "Primary family of 4 at the Bonferroni-adjusted level; every other cell is exploratory. Pre-registered in evals/hrt/PLAN.md; run once on held-out seeds.", "generated_at": res.get("generated_at") or "1970-01-01T00:00:00Z"},
        "statement": stmt, "label": "synthetic, held-out seeds, single frozen run",
        "rows": rows, "primary_family": fam, "scoreboard": res["rows"], "recorded": res.get("recorded"), "not_scored": res.get("not_scored"),
        "replicates": res["replicates"], "split_label": res.get("split_label"), "code_fingerprint": res.get("code_fingerprint"),
        "limitations": [{"id": i, "severity": s, "text": t} for i, s, t in DECISION_LIMITS],
    }


def recorded_section(part: str) -> dict[str, Any]:
    """The report section for ``ledger`` or ``decisions``; raises FileNotFoundError (shown as pending with the reason) if the held-out run has not been made."""
    res = recorded(part)
    if res is None:
        raise FileNotFoundError(f"hrt {part}: the single frozen held-out run (python -m understudy_engine.hrt.run heldout --part {part}) has not been made; a dev result is never shown as evidence")
    return shape_ledger(res) if part == "ledger" else shape_decisions(res)
