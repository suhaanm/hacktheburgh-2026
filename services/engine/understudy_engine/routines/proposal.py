"""Proposal copy (HND-1): what the routine does, how often, hours saved with an interval, what it touches, what it never does.

Plain, specific, no marketing. Everything is filled from numbers already computed; nothing is generated by a model.
"""
from __future__ import annotations

from typing import Any


def how_often(count: int, span_days: float) -> str:
    weeks = max(1, round(span_days / 7))
    return f"about {count} times in {weeks} week{'s' if weeks != 1 else ''}"


def hours_text(hours: list[float], horizon_weeks: int) -> str:
    lo, hi = hours
    if hi < 0.1:
        return f"under 0.1 hours over the next {horizon_weeks} weeks"
    return f"about {lo:.1f} to {hi:.1f} hours over the next {horizon_weeks} weeks"


def never_list(template: dict[str, Any] | None, risk_irreversible: list[str]) -> list[str]:
    if template and template.get("never"):
        return list(template["never"])
    return [p for p in risk_irreversible[:4]] or ["submit"]


def build_proposal(*, title: str, template: dict[str, Any] | None, medoid: list[str], count: int, span_days: float,
                   hours: list[float], horizon_weeks: int, risk_irreversible: list[str]) -> dict[str, Any]:
    what = (template or {}).get("proposal", {}).get("what") or (
        "Do these steps for you when the same kind of case comes up: " + ", then ".join(c.replace("_", " ").lower() for c in dict.fromkeys(medoid)) + "."
    )
    touches = list((template or {}).get("touches") or [])
    return {
        "what": what,
        "how_often": how_often(count, span_days),
        "hours_saved_text": hours_text(hours, horizon_weeks),
        "touches": touches,
        "never": never_list(template, risk_irreversible),
        "title": title,
    }
