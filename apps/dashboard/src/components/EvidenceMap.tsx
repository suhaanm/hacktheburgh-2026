import { useEffect, useState } from "react";
import { fmtPct } from "../lib/format";
import { ORIGIN_NOTE, STATUS_LABEL, describeSection, mapCounts, nText, type MapRow, type MapStatus } from "../lib/evidence";
import { ChartFoot, Note } from "./common";
import type { AnalyticMeta } from "../types";

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => !!v && typeof v === "object" && !Array.isArray(v);
const isNum = (v: unknown): v is number => typeof v === "number" && Number.isFinite(v);

/** The origin badge for one section: dashed for anything that is not a real person, a plain "live" for the study. */
export function OriginPill({ row }: { row: Pick<MapRow, "kind" | "originLabel"> }) {
  const data = row.kind === "live" ? "real" : row.kind === "simulated" ? "simulated" : row.kind === "mixed" ? "mixed" : "synthetic";
  return <span className="pill pill--origin" data-origin={data} title={ORIGIN_NOTE[row.kind]}>{row.originLabel}</span>;
}

function StatusPill({ status }: { status: MapStatus }) {
  const glyph = status === "ok" ? "✓" : status === "failed" ? "✕" : "·";
  return <span className="pill pill--status" data-status={status}><span className="pill__glyph-char" aria-hidden="true">{glyph}</span>{STATUS_LABEL[status]}</span>;
}

/** Every section of the report in one place: where it came from, how many, whether it reports intervals, and whether it has run. */
export function EvidenceMap({ rows, onGo }: { rows: MapRow[]; onGo: (id: string) => (e: { preventDefault: () => void }) => void }) {
  const c = mapCounts(rows);
  const [open, setOpen] = useState(true);
  const ok = rows.filter((r) => r.status === "ok");
  const waiting = rows.filter((r) => r.status !== "ok");
  const anySim = rows.some((r) => r.kind === "simulated");
  return (
    <section className="ev-map" aria-labelledby="map-h">
      <div className="section__head">
        <h2 className="section__title" id="map-h">Every part of the report</h2>
        <p className="section__sub">{c.ok} of {c.total} have results{c.pending ? `, ${c.pending} pending` : ""}{c.not_run ? `, ${c.not_run} not run` : ""}{c.failed ? `, ${c.failed} failed` : ""}. Each row says where its data came from and how much of it there is.</p>
      </div>
      <details className="details-lite" open={open} onToggle={(e) => setOpen((e.currentTarget as HTMLDetailsElement).open)}>
        <summary>{open ? "Hide the map" : "Show the map"}</summary>
        <div className="table-wrap">
          <table className="table ev-map__table">
            <thead><tr><th>Section</th><th>Origin</th><th className="num">n</th><th className="hide-narrow">95% intervals</th><th>Status</th></tr></thead>
            <tbody>
              {[...ok, ...waiting].map((r) => <MapLine key={r.section} r={r} onGo={onGo} />)}
            </tbody>
          </table>
        </div>
      </details>
      <p className="note">{anySim ? "Simulated participants are language models playing workers. They are not people, and no number here treats them as people. " : ""}Synthetic means generated by our own code. Live means measured from real people, and the live study has n = 4.</p>
    </section>
  );
}

function MapLine({ r, onGo }: { r: MapRow; onGo: (id: string) => (e: { preventDefault: () => void }) => void }) {
  const target = r.anchor ?? `sec-${r.section}`;
  const go = (e: { preventDefault: () => void }) => {
    // A section drawn under "Other sections" opens when you go to it.
    const el = document.getElementById(target);
    if (el instanceof HTMLDetailsElement) el.open = true;
    onGo(target)(e);
  };
  return (
    <tr data-status={r.status}>
      <td>
        <a href={`#${target}`} onClick={go}>{r.title}</a>
        {r.label && <span className="u-muted"> · {r.label}</span>}
        {r.status !== "ok" && r.reason && <span className="ev-map__why">{r.reason}</span>}
      </td>
      <td><OriginPill row={r} /></td>
      <td className="num">{r.status === "ok" || r.n ? nText(r) : "none yet"}</td>
      <td className="hide-narrow">{r.intervals === "yes" ? "reported" : r.intervals === "no" ? "none in this section" : "not applicable"}</td>
      <td><StatusPill status={r.status} /></td>
    </tr>
  );
}

/** Sections the page has no block of their own for, read from their envelope: nothing here knows them by name. */
export function OtherSections({ rows, sections }: { rows: MapRow[]; sections: Record<string, unknown> }) {
  if (rows.length === 0) return null;
  return (
    <section className="ev-block" id="other" aria-labelledby="other-h">
      <div className="stack" style={{ gap: "var(--space-2)" }}>
        <p className="t-label">Other sections of the report</p>
        <h2 className="ev-claim" id="other-h">The rest of what the report holds</h2>
        <p className="ev-note">These have no chart of their own yet. Each is read from what it reports: numbers, tables and the caveats it carries. A new section the eval track adds appears here on its own.</p>
      </div>
      <div className="stack" style={{ gap: "var(--space-3)" }}>
        {rows.map((r) => <Other key={r.section} r={r} s={sections[r.section]} />)}
      </div>
    </section>
  );
}

function Other({ r, s }: { r: MapRow; s: unknown }) {
  const v = describeSection(s);
  const meta = isObj(s) && isObj(s.meta) ? (s.meta as unknown as AnalyticMeta) : null;
  return (
    <details className="ev-other" id={`sec-${r.section}`}>
      <summary>
        <span className="ev-other__title">{r.title}</span>
        <OriginPill row={r} />
        <span className="t-data u-muted">{nText(r)}</span>
        <StatusPill status={r.status} />
      </summary>
      <div className="stack">
        {r.status !== "ok" ? <Note>{r.reason ?? "This section has not produced a result."}</Note> : (
          <>
            {r.label && <p className="note">{r.label}</p>}
            {v.statement && <p className="ev-note">{v.statement}</p>}
            {v.facts.length > 0 && <ul className="plain-list ev-facts">{v.facts.map(([k, x]) => <li key={k} className="ev-note">{k}: <b className="tabular">{x}</b></li>)}</ul>}
            {v.tables.map((t) => (
              <div key={t.name} className="stack" style={{ gap: "var(--space-2)" }}>
                <span className="t-label">{t.name}{t.total > t.rows.length ? ` (first ${t.rows.length} of ${t.total})` : ""}</span>
                <div className="table-wrap"><table className="table">
                  <thead><tr>{t.cols.map((c) => <th key={c}>{c.replace(/_/g, " ")}</th>)}</tr></thead>
                  <tbody>{t.rows.map((row, i) => <tr key={i}>{t.cols.map((c) => <td key={c} className={isNum(Number(row[c])) && row[c] !== "" ? "num" : undefined}>{row[c]}</td>)}</tr>)}</tbody>
                </table></div>
              </div>
            ))}
            {v.caveats.length > 0 && (
              <details className="details-lite"><summary>Caveats from the engine ({v.caveats.length})</summary>
                <ul className="plain-list">{v.caveats.map((c) => <li key={c} className="ev-note">{c}</li>)}</ul></details>
            )}
            {v.limits.length > 0 && (
              <details className="details-lite"><summary>Limits of this section ({v.limits.length})</summary>
                <ul className="plain-list">{v.limits.map((c) => <li key={c} className="ev-note">{c}</li>)}</ul></details>
            )}
            {v.facts.length === 0 && v.tables.length === 0 && !v.statement && <p className="note">This section reports no numbers the page can show. Its envelope says: n = {nText(r)}.</p>}
            <ChartFoot meta={meta} />
          </>
        )}
      </div>
    </details>
  );
}

/* -- Privacy: the canary check and which layers it covers ------------------------------------------------------------ */

const CANARY_WORDS: Record<string, string> = {
  registered: "its own flow", adapter: "through the privacy layer's adapter", pure_compute: "no model path (pure compute)", not_applicable: "no model path",
  none_registered: "none yet", not_present: "not present", reference: "reference flow",
};

/** The privacy block: planted strings found in outbound requests, the image gate, and which layers have a real-code check. All numbers come from the report. */
export function PrivacyEvidence({ s, row }: { s: Obj | null; row: MapRow | null }) {
  if (!s || (typeof s.status === "string" && s.status !== "ok")) {
    return (
      <section className="ev-block" id="privacy" aria-labelledby="privacy-h">
        <div className="stack" style={{ gap: "var(--space-2)" }}>
          <p className="t-label">Does anything private leave the laptop?</p>
          <h2 className="ev-claim" id="privacy-h">The privacy check</h2>
        </div>
        <Note>{(s && typeof s.reason === "string" && s.reason) || "The report has no privacy section yet. Run make eval to write it."}</Note>
      </section>
    );
  }
  const h = (isObj(s.headline) ? s.headline : {}) as Obj;
  const img = (isObj(s.image) ? s.image : {}) as Obj;
  const cov = (Array.isArray(s.coverage) ? s.coverage : []).filter(isObj);
  const meta = isObj(s.meta) ? (s.meta as unknown as AnalyticMeta) : null;
  const unatt = (isObj(img.unattended_real_screen) ? img.unattended_real_screen : null) as { attempts?: number; reached_a_provider?: number } | null;
  const blockedBy = Object.entries((isObj(img.blocked_by_reason) ? img.blocked_by_reason : {}) as Record<string, number>);
  const cs = (isObj(h.coverage_summary) ? h.coverage_summary : {}) as Obj;
  const gaps = [...new Set([...(Array.isArray(h.layers_without_integration_flows) ? h.layers_without_integration_flows : []), ...(Array.isArray(cs.gaps) ? cs.gaps : [])])] as string[];
  const notTested = isObj(s.scan_sensitivity) && Array.isArray((s.scan_sensitivity as Obj).not_tested) ? ((s.scan_sensitivity as Obj).not_tested as string[]) : [];
  const limits = (Array.isArray(s.limitations) ? s.limitations : []).filter(isObj).map((l) => String(l.text ?? "")).filter(Boolean);
  const sentImages = isNum(img.sent) ? img.sent : null;
  return (
    <section className="ev-block" id="privacy" aria-labelledby="privacy-h">
      <div className="stack" style={{ gap: "var(--space-2)" }}>
        <p className="t-label">Does anything private leave the laptop?</p>
        <h2 className="ev-claim" id="privacy-h">
          {isNum(h.planted) && isNum(h.requests) && isNum(h.runs)
            ? <>{h.planted.toLocaleString("en-GB")} planted test strings were searched for in {h.requests.toLocaleString("en-GB")} outbound requests across {h.runs} runs: {isNum(h.leaked) ? h.leaked : "?"} leaked.{isNum(h.leak_rate_upper_95) ? ` With nothing found, the leak rate is at most ${fmtPct(h.leak_rate_upper_95, 2)} (one-sided 95% bound).` : ""}</>
            : "The privacy check"}
        </h2>
        {row && <div className="row"><OriginPill row={row} /><span className="t-data u-muted">{nText(row)}</span></div>}
      </div>

      <div className="stats">
        {isNum(h.controls_passed) && isNum(h.controls_total) && <div className="stat"><span className="stat__label">Controls that must fail, did</span><span className="stat__value tabular">{h.controls_passed} of {h.controls_total}</span><span className="stat__meta">A check that cannot fail proves nothing</span></div>}
        {typeof h.scan_detects_known_rewrites === "string" && <div className="stat"><span className="stat__label">Known rewrites found</span><span className="stat__value tabular">{h.scan_detects_known_rewrites}</span><span className="stat__meta">case, separators, URL encoding, base64, hex</span></div>}
        {isNum(h.scan_false_positives) && <div className="stat"><span className="stat__label">False alarms on clean text</span><span className="stat__value tabular">{h.scan_false_positives}</span></div>}
      </div>

      {(isNum(h.image_runs) || sentImages != null || unatt) && (
        <div className="stack" data-testid="ev-images">
          <p className="t-label">Screen frames</p>
          <div className="stats">
            {isNum(h.image_runs) && <div className="stat"><span className="stat__label">Image runs</span><span className="stat__value tabular">{h.image_runs}</span></div>}
            {sentImages != null && <div className="stat"><span className="stat__label">Frames sent</span><span className="stat__value tabular">{sentImages}</span></div>}
            {blockedBy.length > 0 && <div className="stat"><span className="stat__label">Frames blocked</span><span className="stat__value tabular">{blockedBy.reduce((a, [, n]) => a + n, 0)}</span><span className="stat__meta">{blockedBy.map(([k, n]) => `${k.replace(/_/g, " ")} ${n}`).join(", ")}</span></div>}
            {unatt && isNum(unatt.attempts) && <div className="stat"><span className="stat__label">Unattended real-screen frames that reached a model</span><span className="stat__value tabular">{unatt.reached_a_provider ?? "?"} of {unatt.attempts}</span><span className="stat__meta">attempts, all blocked at the gate</span></div>}
            {isNum(h.image_leaks) && <div className="stat"><span className="stat__label">Frame residue found on disk or in logs</span><span className="stat__value tabular">{h.image_leaks}</span></div>}
          </div>
        </div>
      )}

      {cov.length > 0 && (
        <div className="stack" data-testid="ev-layers">
          <p className="t-label">Which layers have a check that runs their real code</p>
          <div className="table-wrap"><table className="table">
            <thead><tr><th>Layer</th><th>How it is checked</th><th>Real code</th><th className="num">Runs</th><th className="num">Requests</th><th className="num">Planted</th><th className="num">Leaked</th></tr></thead>
            <tbody>{cov.map((c) => {
              const real = c.real_code_flow === true;
              const name = String(c.layer ?? "");
              const noPath = c.pure_compute === true || c.canary_flow === "pure_compute" || c.canary_flow === "not_applicable";
              const inGap = gaps.includes(name) || (!real && !noPath && c.present === true);
              return (
                <tr key={name} data-gap={inGap}>
                  <td>{name.replace(/_/g, " ")}</td>
                  <td>{CANARY_WORDS[String(c.canary_flow ?? "")] ?? String(c.canary_flow ?? "").replace(/_/g, " ")}</td>
                  <td>{real ? <span><span aria-hidden="true">✓</span> yes</span> : noPath ? <span className="u-muted">no model path</span> : <span><span aria-hidden="true">✕</span> not yet</span>}</td>
                  <td className="num">{isNum(c.runs) ? c.runs : ""}</td><td className="num">{isNum(c.requests) ? c.requests : ""}</td>
                  <td className="num">{isNum(c.planted) ? c.planted.toLocaleString("en-GB") : ""}</td><td className="num">{isNum(c.leaked) ? c.leaked : ""}</td>
                </tr>
              );
            })}</tbody>
          </table></div>
          {gaps.length > 0 && <p className="ev-note">No real-code check exists yet for: {gaps.map((g) => g.replace(/_/g, " ")).join(", ")}. Until one does, nothing here says those layers do not leak.</p>}
        </div>
      )}

      <p className="ev-note">This is evidence from planted strings, not a proof.{notTested.length ? ` It does not test: ${notTested.join(", ")}.` : ""}</p>
      {limits.length > 0 && (
        <details className="details-lite"><summary>Limits of the privacy check ({limits.length})</summary>
          <ul className="plain-list">{limits.map((t) => <li key={t} className="ev-note">{t}</li>)}</ul></details>
      )}
      <ChartFoot meta={meta} />
    </section>
  );
}

/** A section under "Other sections" opens when the page is opened at its link, or when the link is followed. */
export function useHashOpen() {
  useEffect(() => {
    const open = () => { const id = window.location.hash.replace(/^#/, ""); const el = id ? document.getElementById(id) : null; if (el instanceof HTMLDetailsElement) el.open = true; };
    open();
    window.addEventListener("hashchange", open);
    return () => window.removeEventListener("hashchange", open);
  }, []);
}
