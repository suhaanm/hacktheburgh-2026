#!/usr/bin/env python3
"""One live proof that a forecast is written before its outcome exists and scored afterwards (for the video; no model call, no network, no real data).

    python3 scripts/hrt_ledger_proof.py [--wait 3]        (from the repository root; needs the engine's Python environment: `uv run --package understudy-engine python scripts/hrt_ledger_proof.py`)

It fits a small stuck-hazard model on a few generated people, takes a bin of a generated person the model has never seen (picked by position, never by its outcome:
the forecast can be wrong and the script prints it either way), writes the forecast to a hash-chained ledger
(with the online base rate beside it), waits for the horizon on the real clock, writes the outcome, scores the pair, verifies the chain, and then edits the old row
to show that the chain refuses it. The ledger lives in a temporary directory and is deleted. Everything is generated by us; nothing here is a result.
"""
from __future__ import annotations

import argparse
import copy
import datetime as dt
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "engine"))


def _utc(t: float) -> str:
    return dt.datetime.fromtimestamp(t, dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def run(wait_s: float = 3.0, *, seed: int = 9001, clock=time.time, sleep=time.sleep) -> list[str]:
    import numpy as np

    from understudy_engine.hazard.features import build_bins
    from understudy_engine.hazard.model import HazardModel
    from understudy_engine.hazard.sim import simulate_people
    from understudy_engine.hrt.ledger import Ledger, LedgerError

    train, _ = simulate_people(4, 40, seed=3)
    tab_train = build_bins(train)
    model = HazardModel("full", 3.0).fit(tab_train, np.arange(tab_train.n))
    base_rate = float(tab_train.y.mean())
    unseen, _ = simulate_people(1, 6, seed=seed)
    tab = build_bins(unseen)
    k = int(np.argmax(tab.t > tab.t.min() + 90))                         # chosen by position only, never by how it turns out: the first bin more than 90 s in
    p_model = float(model.predict(tab, np.array([k]))[0])
    y = int(tab.y[k])

    lines: list[str] = []
    with tempfile.TemporaryDirectory() as d:
        led = Ledger(path=Path(d) / "predictions.jsonl")
        t0 = clock()
        pid = led.predict(kind="stuck_hazard", stream="a-generated-person", made_at=t0, horizon_s=wait_s, primary="model", version="hazard-full",
                          forecasts={"model": p_model, "online_base": base_rate})
        row0 = led.entries[0]
        lines.append(f"BEFORE  {_utc(t0)}  forecast P(no progress in the next minute) = {p_model:.2f} (model), {base_rate:.2f} (base rate)   outcome: not yet known   hash {row0['hash'][:12]}")
        sleep(wait_s)
        t1 = clock()
        led.resolve(pid, resolved_at=t1, outcome=y)
        row1 = led.entries[1]
        lines.append(f"AFTER   {_utc(t1)}  outcome = {y} ({'no progress' if y else 'progress'})   written after the horizon, hash {row1['hash'][:12]} chained to {row1['prev'][:12]}")
        arr_ll = lambda p: -(y * np.log(np.clip(p, 0.01, 0.99)) + (1 - y) * np.log(1 - np.clip(p, 0.01, 0.99)))  # noqa: E731
        lines.append(f"SCORE   log loss {arr_ll(p_model):.3f} for the model, {arr_ll(base_rate):.3f} for the base rate; one forecast, so not evidence, only the mechanism")
        led.verify()
        try:                                                                 # the tamper test: edit the old forecast to look better, in a copy of the record
            forged = Ledger(entries=copy.deepcopy(led.entries))
            forged.entries[0]["forecasts"]["model"] = 0.99 if y else 0.01
            forged.verify()
            lines.append("TAMPER  NOT CAUGHT (this is a bug)")
        except LedgerError as e:
            lines.append(f"CHAIN   verified; editing the old forecast afterwards is refused: {e}")
        try:
            led.resolve(pid, resolved_at=clock(), outcome=1 - y)
        except LedgerError as e:
            lines.append(f"REWRITE refused: {e}")
        led.close()
    return lines


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wait", type=float, default=3.0, help="seconds between the forecast and its outcome (the horizon)")
    ap.add_argument("--seed", type=int, default=9001, help="which generated person to forecast (the bin is picked by position, never by its outcome, so the forecast may be wrong)")
    args = ap.parse_args(argv)
    for line in run(args.wait, seed=args.seed):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
